    #[core::prelude::v1::test]
    fn test_text_input_grapheme_boundaries_unicode_and_emojis() {
        // "Olá 👋 Mundo" -> 'á' is 2 bytes, '👋' is 4 bytes
        let input = MockTextInputLogic::new("Olá 👋 Mundo");
        // 'O'(1), 'l'(1), 'á'(2) -> index 4 is space
        assert_eq!(input.previous_boundary(4), 2); // skips 'á' (2 bytes)
        assert_eq!(input.previous_boundary(2), 1);
        assert_eq!(input.previous_boundary(0), 0);

        // 👋 is at index 5..9
        let wave_start = 5;
        let wave_end = 9;
        assert_eq!(input.next_boundary(wave_start), wave_end);
        assert_eq!(input.previous_boundary(wave_end), wave_start);
    }

    #[core::prelude::v1::test]
    fn test_text_input_utf16_conversion_roundtrip() {
        let input = MockTextInputLogic::new("A 👋 B 🌍 C");
        let utf8_len = input.content.len();
        let utf16_len = input.content.encode_utf16().count();

        assert_eq!(input.offset_to_utf16(utf8_len), utf16_len);
        assert_eq!(input.offset_from_utf16(utf16_len), utf8_len);

        // Point to before wave emoji
        let idx_wave = 2; // "A "
        assert_eq!(input.offset_to_utf16(idx_wave), 2);
        assert_eq!(input.offset_from_utf16(2), idx_wave);

        // Point to after wave emoji (👋 takes 2 utf16 units, 4 utf8 bytes)
        let idx_after_wave = idx_wave + 4;
        assert_eq!(input.offset_to_utf16(idx_after_wave), 4);
        assert_eq!(input.offset_from_utf16(4), idx_after_wave);
    }

    #[core::prelude::v1::test]
    fn test_text_input_replace_range_insert_and_delete() {
        let mut input = MockTextInputLogic::new("Hello World");

        // Delete " World" (index 5..11)
        input.replace_range(5..11, "");
        assert_eq!(input.content, "Hello");
        assert_eq!(input.cursor_offset(), 5);

        // Insert ", Wazzup!" at index 5
        input.replace_range(5..5, ", Wazzup!");
        assert_eq!(input.content, "Hello, Wazzup!");
        assert_eq!(input.cursor_offset(), 14);

        // Overwrite "Hello" with "Hi" (0..5)
        input.replace_range(0..5, "Hi");
        assert_eq!(input.content, "Hi, Wazzup!");
        assert_eq!(input.cursor_offset(), 2);
    }
